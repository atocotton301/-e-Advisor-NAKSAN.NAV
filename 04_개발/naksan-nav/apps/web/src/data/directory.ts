// 위치 붙이기: 트랙·학과 사무실은 학과 안내의 사무실, 부서는 「기구표 및 부서안내」의 위치.
{
  const trackRoom = new Map(COLLEGES.flatMap((c) => c.units.flatMap((u) => u.tracks.map((t) => [t.name, t.room] as const))));
  const n = (s: string) => s.replace(/[\s·ㆍ()（）]/g, "");
  const byName = new Map(DIRECTORY.map((c) => [n(c.name), c]));
  for (const c of DIRECTORY) if (c.kind === "트랙·학과" && !c.room) c.room = trackRoom.get(c.name) || undefined;
  for (const o of ORG_UNITS) {
    const base = o.name.replace(/ 사무실$/, "");
    const hit = byName.get(n(o.name)) ?? byName.get(n(base));
    if (hit) {
      if (o.room) hit.room = o.room;
      continue;
    }
    DIRECTORY.push({
      name: o.name,
      unit: o.name.includes("대학원") ? "대학원" : o.name.endsWith("사무실") ? "학과 사무실" : "본부·부속기관",
      kind: o.name.includes("대학원") ? "대학원" : o.name.includes("교학팀") ? "교학팀" : o.name.endsWith("사무실") ? "트랙·학과" : "행정·지원",
      phone: o.phone || "번호 미기재",
      room: o.room || undefined,
    });
  }
}

// 교수 연구실 호수 붙이기 (이름이 같으면 소속으로 구분)
{
  const n = (s: string) => s.replace(/[\s·ㆍ&]/g, "").replace(/트랙|학과|학부|전공/g, "");
  const profs = DIRECTORY.filter((c) => c.kind === "교수 연구실");
  for (const [name, room, unit, note] of PROF_ROOMS) {
    const label = /^\d+$/.test(room) ? `연구실 ${room}호` : `연구실 ${room}`;
    const same = profs.filter((p) => p.name.split(" ")[0] === name);
    const hit = same.length > 1 ? same.find((p) => n(p.unit).includes(n(unit).slice(0, 2))) ?? same[0] : same[0];
    if (hit) {
      hit.room = note ? `${label} (${note})` : label;
      continue;
    }
    DIRECTORY.push({ name: `${name} 교수`, unit, kind: "교수 연구실", phone: "번호 미기재", room: label });
  }
}
