function track(name: string, family: Family, room: string, phone: string, extra: Partial<Track> = {}): Track {
  return { id: name, name, family, room, phone, ...extra };
}

/** 단일 학과는 학과 자체를 하나의 트랙처럼 다룬다. */
function dept(name: string, family: Family, room: string, phone: string, extra: Partial<Track> = {}): Unit {
  return { name, tracks: [track(name, family, room, phone, extra)] };
}

