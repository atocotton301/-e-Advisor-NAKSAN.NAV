/** 같은 교수(이름+전공)는 하나로 합치고 소속·번호를 모은다. */
export const PROFESSORS: Professor[] = (() => {
  const map = new Map<string, Professor>();
  for (const line of PROFESSOR_TSV.split("\n")) {
    const [name = "", rank = "", unit = "", major = "", phone = ""] = line.split("\t").map((s) => s.trim());
    if (!name) continue;
    const key = `${name}|${major}`;
    const p = map.get(key);
    if (p) {
      if (!p.units.includes(unit)) p.units.push(unit);
      if (phone && !p.phone.split(", ").includes(phone)) p.phone = p.phone ? `${p.phone}, ${phone}` : phone;
    } else map.set(key, { name, rank, units: [unit], major, phone });
  }
  return [...map.values()];
})();
